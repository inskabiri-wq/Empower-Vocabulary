  // One CSV serialiser for both downloads. The BOM makes Excel open a
  // UTF-8 file with Turkish characters intact instead of as mojibake.
  function toCsv(rows) {
    var NL = String.fromCharCode(13) + String.fromCharCode(10);
    var needsQuote = new RegExp("[\",]|" + String.fromCharCode(10));
    return String.fromCharCode(0xFEFF) + rows.map(function (row) {
      return row.map(function (v) {
        var t = String(v == null ? "" : v);
        return needsQuote.test(t) ? '"' + t.replace(/"/g, '""') + '"' : t;
      }).join(",");
    }).join(NL);
  }
  // The rows the sheet named but gave no address for, handed back as a CSV
  // with an empty Email column to fill in. Excel opens it, the office types
  // the addresses, and the same file goes back through the importer.
  // ONE FILE PER SHEET, because the importer takes them separately.
  //
  // The first version emitted a single mixed CSV with a `role` column. The
  // importer never reads that column, so uploading the combined file as the
  // teacher sheet would have turned 55 students into teachers. Splitting is
  // the fix; the role column stays only as a label for the human.
  function downloadNeedEmail() {
    var rows = state.needEmail || [];
    if (!rows.length) return;

    var mod = ((($('riModule') || {}).value || 'module').trim()
                .replace(/[^A-Za-z0-9_.-]+/g, '_')) || 'module';

    function csvFor(kind, source) {
      var mine = rows.filter(function (x) { return x.kind === kind; });
      if (!mine.length) return 0;
      // Look each person up in the parsed rows so class and level come too;
      // asking someone to retype those is how mistakes get in.
      var lines = [['name', 'email', 'class', 'level']];
      mine.forEach(function (x) {
        var src = null, all = source || [];
        for (var i = 0; i < all.length; i++) {
          if (String(all[i].name || '').trim() === String(x.name || '').trim()) { src = all[i]; break; }
        }
        lines.push([x.name || '', '', (src && src.class) || '', (src && src.level) || '']);
      });
      var blob = new Blob([toCsv(lines)], { type: 'text/csv;charset=utf-8;' });
      var url = URL.createObjectURL(blob);
      var a = document.createElement('a');
      a.href = url;
      a.download = 'add-emails-' + kind + 's-' + mod + '.csv';
      document.body.appendChild(a); a.click(); document.body.removeChild(a);
      setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
      return mine.length;
    }

    var nT = csvFor('teacher', state.teachers);
    var nS = csvFor('student', state.students);
    var parts = [];
    if (nT) parts.push(nT + ' teacher(s)');
    if (nS) parts.push(nS + ' student(s)');
    setStatus('Downloaded ' + parts.join(' and ') + ' as separate files. Fill in the ' +
      'Email column in each, then upload the teachers file as the TEACHER sheet and the ' +
      'students file as the STUDENT sheet.', '#3b82f6');
  }

