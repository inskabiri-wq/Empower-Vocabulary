  // ---- class QR codes (one scannable code per class, printable) ----
  var qrLoading = null;
  function ensureQr() {
    if (window.qrcode) return Promise.resolve();
    if (qrLoading) return qrLoading;
    qrLoading = new Promise(function (resolve, reject) {
      var s = document.createElement('script');
      s.src = 'teacher/js/vendor/qrcode.min.js';
      s.onload = function () { resolve(); };
      s.onerror = function () { reject(new Error('Could not load the QR generator.')); };
      document.head.appendChild(s);
    });
    return qrLoading;
  }
  function buildJoinUrl(c) {
    return location.origin + '/join.html?c=' + encodeURIComponent(c._key || '') + '&k=' + encodeURIComponent(c.joinCode || '');
  }
  // ONE <img>, NOT A THOUSAND <rect>s.
  //
  // createSvgTag returns about 18KB of markup per code, roughly a thousand
  // rectangles. Sixteen classes meant ~290KB of string concatenation parsed
  // into ~16,000 DOM nodes in a single innerHTML assignment, which is what
  // made this panel crawl and what made "Print this class" - which rebuilds
  // them all in a new window - look like a hang.
  //
  // The same SVG encoded as a data URI is one image node. The browser decodes
  // it off the main thread and the card DOM stays flat.
  //
  // `scalable: true` is also dropped: it omits width and height, so the SVG
  // had only a viewBox and collapsed inside the card's `line-height:0`
  // wrapper. That is why the cards showed a class code and no QR at all.
  var qrCache = Object.create(null);
  function qrDataUri(url) {
    if (qrCache[url]) return qrCache[url];
    var qr = qrcode(0, 'M');
    qr.addData(url);
    qr.make();
    var svg = qr.createSvgTag({ cellSize: 4, margin: 2 });
    qrCache[url] = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
    return qrCache[url];
  }
